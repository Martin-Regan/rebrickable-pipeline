CREATE OR REPLACE VIEW TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.DIM_COLORS AS
SELECT
    RAW_JSON:id::INT           AS COLOR_ID,
    RAW_JSON:name::STRING      AS COLOR_NAME,
    RAW_JSON:rgb::STRING       AS RGB,
    RAW_JSON:is_trans::BOOLEAN AS IS_TRANSPARENT,
    RAW_JSON:num_parts::INT    AS NUM_PARTS,
    RAW_JSON:num_sets::INT     AS NUM_SETS,
    RAW_JSON:year_from::INT    AS YEAR_FROM,
    RAW_JSON:year_to::INT      AS YEAR_TO,
    LOADED_AT
FROM TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.RAW_COLORS;

