-- Inventory tables (loaded from Rebrickable bulk CSV downloads)

CREATE OR REPLACE TABLE TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.RAW_INVENTORIES (
    INVENTORY_ID NUMBER(38,0),
    VERSION      NUMBER(38,0),
    SET_NUM      VARCHAR(100),
    LOADED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.RAW_INVENTORY_MINIFIGS (
    INVENTORY_ID NUMBER(38,0),
    FIG_NUM      VARCHAR(100),
    QUANTITY     NUMBER(38,0),
    LOADED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Fact view joining minifigs to sets and themes via inventories

CREATE OR REPLACE VIEW TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.FCT_MINIFIG_APPEARANCES AS
SELECT
    m.FIG_NUM,
    m.FIG_NAME,
    m.NUM_PARTS    AS FIG_NUM_PARTS,
    m.IMAGE_URL    AS FIG_IMAGE_URL,
    im.QUANTITY,
    s.SET_NUM,
    s.SET_NAME,
    s.RELEASE_YEAR,
    s.NUM_PARTS    AS SET_NUM_PARTS,
    t.THEME_ID,
    t.THEME_NAME,
    t.PARENT_THEME_ID
FROM TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.RAW_INVENTORY_MINIFIGS im
JOIN TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.RAW_INVENTORIES i
    ON im.INVENTORY_ID = i.INVENTORY_ID
JOIN TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.DIM_MINIFIGS m
    ON im.FIG_NUM = m.FIG_NUM
JOIN TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.DIM_SETS s
    ON i.SET_NUM = s.SET_NUM
JOIN TIL_PORTFOLIO_PROJECTS.MR_REBRICKABLE.DIM_THEMES t
    ON s.THEME_ID = t.THEME_ID;
